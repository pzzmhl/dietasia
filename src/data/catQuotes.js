/**
 * Restituisce una citazione casuale in base al contesto
 * @param {'success' | 'cheat' | 'key' | 'neutral' | 'no_log' | 'click_success' | 'click_cheat' | 'click_key' | 'difficult_streak' | 'success_streak' | 'bounce_back' | 'after_absence' | 'late_night' | 'frequent_opens' | 'stats_view' | 'special_days' | 'modified_log' | 'last_key'} context
 */
export function getRandomCatQuote(context = 'neutral') {
  const pool = CAT_QUOTES[context] || CAT_QUOTES.no_log;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
}

/**
 * Seleziona in modo intelligente la citazione situazionale ideale per il Gatto
 * @param {
 *   todayStatus?: 'success' | 'cheat' | 'key' | null,
 *   yesterdayStatus?: 'success' | 'cheat' | 'key' | null,
 *   consecutiveSuccess?: number,
 *   consecutiveCheat?: number,
 *   hasAbsence?: boolean,
 *   isStatsView?: boolean,
 *   isSpecialDay?: boolean,
 *   openCountToday?: number,
 *   now?: Date
 * } state
 * @returns {string} Battuta del gatto
 */
export function getSmartSituationalCatQuote(state = {}) {
  const now = state.now || new Date();
  const hours = now.getHours();
  const minutes = now.getMinutes();
  const isNight = (hours >= 22 && minutes >= 30) || (hours < 5);

  // 1. Notte (22:30 - 05:00)
  if (isNight) {
    return getRandomCatQuote('late_night');
  }

  // 2. Molte aperture oggi (5+)
  if (state.openCountToday && state.openCountToday >= 5) {
    return getRandomCatQuote('frequent_opens');
  }

  // 3. Schermata statistiche
  if (state.isStatsView) {
    return getRandomCatQuote('stats_view');
  }

  // 4. Giorno speciale / festa
  if (state.isSpecialDay) {
    return getRandomCatQuote('special_days');
  }

  // 5. Rientro dopo assenza
  if (state.hasAbsence) {
    return getRandomCatQuote('after_absence');
  }

  // 6. Più giorni difficili consecutivi (3+)
  if (state.consecutiveCheat && state.consecutiveCheat >= 3) {
    return getRandomCatQuote('difficult_streak');
  }

  // 7. Molti giorni consecutivi rispettati (5+)
  if (state.consecutiveSuccess && state.consecutiveSuccess >= 5) {
    return getRandomCatQuote('success_streak');
  }

  // 8. Oggi rispettato ma ieri non rispettato
  if (state.todayStatus === 'success' && state.yesterdayStatus === 'cheat') {
    return getRandomCatQuote('bounce_back');
  }

  // 9. Stato registrato oggi
  if (state.todayStatus === 'success') {
    return getRandomCatQuote('click_success');
  }
  if (state.todayStatus === 'cheat') {
    return getRandomCatQuote('click_cheat');
  }
  if (state.todayStatus === 'key') {
    return getRandomCatQuote('click_key');
  }

  // 10. Default: oggi non ancora registrato
  return getRandomCatQuote('no_log');
}
